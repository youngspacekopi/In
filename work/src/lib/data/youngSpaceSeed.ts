// Dynamic Date Helpers to ensure live today and past days timestamps
export const getTodayIso = (hours: number, minutes: number = 0): string => {
  const d = new Date();
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

export const getDaysAgoIso = (daysAgo: number, hours: number, minutes: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

